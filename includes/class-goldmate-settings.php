	/**
	 * Pricing tab intro: points at the fetch tab, which owns the rate, profit and tax.
	 *
	 * @return string
	 */
	protected static function pricing_source_desc() {

		$rate = goldmate_reference_rate();
		$shop = goldmate_shop_percentages();

		return sprintf(
			'وزن × قیمت هر گرم (متناسب با عیار) = مبلغ طلا؛ سپس اجرت، سود، متعلقات و مالیات به آن افزوده می‌شود. قیمت روز، درصد سود و درصد مالیات فقط در تب «تنظیمات فراخوانی قیمت» (آیتم gold18) تنظیم می‌شوند — اکنون: %s تومان، سود %s٪، مالیات %s٪.',
			number_format( $rate, 0, '.', ',' ),
			wc_format_localized_decimal( $shop['profit_pct'] ),
			wc_format_localized_decimal( $shop['tax_pct'] )
		);
	}

